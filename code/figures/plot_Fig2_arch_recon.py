def arrow(ax, p0, p1, color=INK, lw=1.0, ms=9, ls="-", rad=0.0, shrinkA=0, shrinkB=0):
    ax.add_patch(FancyArrowPatch(
        p0, p1, arrowstyle="-|>", mutation_scale=ms, color=color, lw=lw,
        linestyle=ls, shrinkA=shrinkA, shrinkB=shrinkB,
        connectionstyle=f"arc3,rad={rad}", zorder=3))


def nbox(ax, cx, cy, w, h, lines, fs=st.FS_ANNOT, tc=ENC_C, subs="", sfs=st.FS_CAPTION_TXT,
         sc=GRAY, fc=ENC_BG, ec=None, lw=1.0, linegap=0.055, fill=True):
    if ec is None:
        ec = tc
    if fill:
        ax.add_patch(FancyBboxPatch(
            (cx - w / 2, cy - h / 2), w, h,
            boxstyle="round,pad=0.004,rounding_size=0.02",
            fc=fc, ec=ec, lw=lw, zorder=2))
    if isinstance(lines, str):
        lines = [lines]
    yt = cy + (len(lines) - 1) / 2 * linegap
    for i, ln in enumerate(lines):
        ax.text(cx, yt - i * linegap, ln, ha="center", va="center",
                fontsize=fs, color=tc, fontweight="bold", zorder=4)
    if subs:
        # subs clears the bottom edge: glyph half-height (~0.032 for 6.5-7pt)
        # + a small margin; +0.018 clipped the descenders (QC-measured).
        ax.text(cx, cy - h / 2 + 0.035, subs, ha="center", va="center",
                fontsize=sfs, color=sc, zorder=4)


def panel_header(ax, tag, title, title_x=0.054, title_fs=13):
    """Panel tag (bold 14 pt) + panel title as two separate text objects, in
    axes coordinates just above the axes (transAxes), both left- and
    bottom-aligned on the SAME baseline (y=1.08). The tag font is 14 pt
    (~12% smaller than the previous 16 pt) so all three tags read as small
    uniform labels, not as part of the title. The title sits at a visually
    consistent ~0.11 in gap right of the tag: per-panel title_x accounts for
    the different panel widths (a 0.054 / b 0.116 / c 0.133), so the tag-to-
    title offset looks identical across panels. Both stay inside the figure
    (no clipping). title_fs defaults to 13 pt; the (b)/(c) titles drop to
    9 pt so the full single-line strings fit their narrower panels (a 13 pt
    single line measured ~3.3-3.4 in vs ~2.6-3.0 in panel width)."""
    ax.text(0.00, 1.08, tag, transform=ax.transAxes, fontsize=14,
            fontweight="bold", color=INK, va="bottom", ha="left", zorder=6)
    ax.text(title_x, 1.08, title, transform=ax.transAxes, fontsize=title_fs,
            fontweight="normal", color=INK, va="bottom", ha="left", zorder=6)


