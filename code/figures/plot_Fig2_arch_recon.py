def main():
    d = np.load(NPZ)
    J_test = d["J_test"]
    J_test_raw = d["J_test_raw"]
    recon = d["recon_test"]
    V = d["V_GRID"]
    reps = d["fig2b_repr_indices"]
    pce = d["fig2b_repr_PCE"]

    # physical-space reconstruction via the frozen J scaler
    with open(J_SCALER, "rb") as f:
        jscal = pickle.load(f)
    recon_phys = jscal.inverse_transform(recon)

    # normalized-space per-sample MSE for (c)
    mse = np.mean((J_test - recon) ** 2, axis=1)
    mean_mse = float(np.mean(mse))
    med_mse = float(np.median(mse))
    print("recon MSE mean/median: %.6e / %.6e" % (mean_mse, med_mse))
    assert abs(mean_mse - 1.211e-5) < 1e-8 and abs(med_mse - 2.969e-6) < 1e-8, "MSE mismatch!"

    # ---------- layout: (a) top full width; (b)+(c) bottom ----------
    for size in ("journal", "large"):
        w = st.set_fig_width(size)
        # Canvas taller (0.74) so the 18 pt panel labels + (two-line) 13 pt
        # titles have a clean band above the axes; top=0.90 is the largest
        # margin that keeps the 18 pt labels inside the figure, and hspace is
        # enlarged so the (b)/(c) header band clears the bottom of panel (a).
        fig = plt.figure(figsize=(w, w * 0.74))
        gs = fig.add_gridspec(2, 2, height_ratios=[1.28, 1.0],
                              width_ratios=[1.15, 1.0],
                              left=0.070, right=0.980, top=0.90, bottom=0.080,
                              wspace=0.30, hspace=0.42)

        # ============ (a) architecture ============
        axa = fig.add_subplot(gs[0, :])
        axa.set_xlim(0, 1.22); axa.set_ylim(0, 1.02)
        axa.axis("off")
        panel_header(axa, "(a)", "VAE-v6 architecture · no cycle-consistency branch",
                     title_x=0.054)
        draw_arch(axa)

        # ============ (b) reconstructions ============
        axb = fig.add_subplot(gs[1, 0])
        for k in range(3):
            i = reps[k]
            col = TERC_COL[k]
            axb.plot(V, J_test_raw[i], color=col, lw=1.2, alpha=0.95)
            axb.plot(V, recon_phys[i], color=col, ls="--", lw=1.1, alpha=0.7)
        # y-limit: photovoltaic operating region + small reverse-bias margin.
        # The extreme reverse-bias tail of the high-PCE sample (J < -300 mA/cm2)
        # leaves the frame; operating-region agreement is the figure's message.
        axb.set_xlim(0, 1.3)
        # extra top padding above the photovoltaic plateau (J ~ 24) so the
        # curves do not crowd the axes top border
        axb.set_ylim(-60, 30)
        axb.set_xlabel("Voltage (V)")
        axb.set_ylabel(r"J (mA cm$^{-2}$)")
        st.configure_axes(axb)

        # two compact legends in the empty lower-left quadrant of panel (b):
        # color -> PCE tercile; line style -> target/decoder
        leg1_handles = [Line2D([], [], color=TERC_COL[k], lw=1.2, ls="-")
                        for k in range(3)]
        leg1 = axb.legend(leg1_handles, TERC_LAB, fontsize=st.FS_LEGEND,
                          frameon=False, loc="lower left",
                          bbox_to_anchor=(0.03, 0.075), handlelength=1.6,
                          borderpad=0.3, labelspacing=0.4)
        axb.add_artist(leg1)
        leg2_handles = [Line2D([], [], color=INK, lw=1.2, ls="-"),
                        Line2D([], [], color=INK, lw=1.1, ls="--")]
        axb.legend(leg2_handles, ["target", "decoder"], fontsize=st.FS_LEGEND,
                   frameon=False, loc="lower left",
                   bbox_to_anchor=(0.03, 0.47), handlelength=1.6,
                   borderpad=0.3, labelspacing=0.4)

        # ============ (c) error distribution ============
        axc = fig.add_subplot(gs[1, 1])
        logmse = np.log10(mse)
        axc.hist(logmse, bins=50, color=BLUE, alpha=0.75,
                 edgecolor="white", linewidth=0.3)
        axc.axvline(np.log10(mean_mse), color=ORANGE, lw=1.2, ls="-",
                    label=r"mean $1.21\times10^{-5}$")
        axc.axvline(np.log10(med_mse), color=INK, lw=1.2, ls="--",
                    label=r"median $2.97\times10^{-6}$")
        axc.set_xlabel(r"$\log_{10}$(normalized MSE)")
        axc.set_ylabel("count")
        st.configure_axes(axc)
        axc.legend(fontsize=st.FS_LEGEND, frameon=False, loc="upper right")

        # panel labels + titles just above their own axes.
        # (b)/(c) titles are single line at 9 pt: at 13 pt the full strings
        # measure ~3.3-3.4 in vs the ~2.6-3.0 in panels, so 13 pt single line
        # clips; 9 pt is the largest size that fits one line inside panel (b)
        # and inside the figure for (c) without touching the label or the
        # right edge. Panel (a) title stays 13 pt.
        panel_header(axb, "(b)", "decoder reconstruction (frozen checkpoint)",
                     title_x=0.116, title_fs=9)
        panel_header(axc, "(c)", "reconstruction error, test set (N = 15,307)",
                     title_x=0.133, title_fs=9)

        stem = os.path.join(OUT_DIR, "Fig2_arch_recon_surgical3"
                            + ("_large" if size == "large" else ""))
        st.save_fig(fig, stem, svg=True)
        print("wrote:", stem)


if __name__ == "__main__":
    main()
