def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def describe_table(path):
    df = pd.read_csv(path, nrows=5)
    n = sum(1 for _ in open(path, encoding="utf-8", errors="replace")) - 1
    return df.columns.tolist(), n


